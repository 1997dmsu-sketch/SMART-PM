import {readFileSync,writeFileSync} from 'node:fs';
const source = new URL('../miniprogram/config/version.json', import.meta.url);
const version = JSON.parse(readFileSync(source, 'utf8'));
const pkg = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
if (version.version !== pkg.version) throw new Error('Update package.json and version.json together first.');
writeFileSync(new URL('../miniprogram/config/version.js', import.meta.url), '// Generated by npm run version:sync; keep JSON metadata out of runtime require.\nmodule.exports = ' + JSON.stringify(version, null, 2) + ';\n');
